#!/usr/bin/env python3
"""Refresh _data/github_projects.yml from the public GitHub API.

The site is static, so the project list is baked in at author time rather than
fetched in the browser: no rate limit for readers, no failure mode on the page,
and the ordering stays deliberate. Re-run after publishing or renaming a repo.
"""
import json, sys, urllib.request, datetime

USER = "sehyeony0518"
# The site itself and the mission site are not portfolio work.
SKIP = {"sehyeony0518.github.io", "Misson2035"}

def main():
    req = urllib.request.Request(
        f"https://api.github.com/users/{USER}/repos?per_page=100&sort=updated",
        headers={"User-Agent": "sehyeony0518.github.io", "Accept": "application/vnd.github+json"},
    )
    repos = json.load(urllib.request.urlopen(req, timeout=30))
    rows = [r for r in repos if not r["fork"] and not r["archived"] and r["name"] not in SKIP]
    # Stars first, then most recently touched.
    rows.sort(key=lambda r: (-r["stargazers_count"], r["pushed_at"]), reverse=False)
    rows.sort(key=lambda r: (r["stargazers_count"], r["pushed_at"]), reverse=True)

    def esc(s):
        return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = [
        "# Generated by bin/fetch_github_projects.py -- do not edit by hand.",
        f"# {datetime.date.today().isoformat()} from https://github.com/{USER}",
        "",
    ]
    for r in rows:
        out.append(f"- name: {esc(r['name'])}")
        out.append(f"  url: {esc(r['html_url'])}")
        out.append(f"  description: {esc(r['description'])}")
        out.append(f"  language: {esc(r['language'])}")
        out.append(f"  stars: {r['stargazers_count']}")
        out.append(f"  updated: {esc(r['pushed_at'][:10])}")
        topics = r.get("topics") or []
        if topics:
            out.append("  topics:")
            out.extend(f"    - {esc(t)}" for t in topics[:4])
        out.append("")
    open("_data/github_projects.yml", "w", encoding="utf-8").write("\n".join(out))
    print(f"wrote _data/github_projects.yml with {len(rows)} repositories")

if __name__ == "__main__":
    sys.exit(main())
